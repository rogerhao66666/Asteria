"""Build the standalone Asteria app (AST-06): ``.venv/bin/python scripts/build_app.py``.

Needs PyInstaller in the build interpreter (``pip install -e ".[pygame,editor,package]"``).
Light users download the result and run it with no Python, PySide6 or pygame installed.

What it makes (in ``dist/``, git-ignored; work files in ``build/app``):

- ``Asteria.app`` (macOS) or the ``Asteria`` folder (Windows / Linux): the editor. PyInstaller
  freezes the interpreter, the whole standard library (so a project's own Python code can import
  what it likes), PySide6, pygame-ce, numpy and ModernGL. The engine is not frozen: it is copied
  as plain source into ``engine/src/asteria`` with ``engine/asset_library`` and the Full
  Verification demo (``engine/reference_projects``), so everything the engine finds from
  ``__file__`` works as in a checkout and an export copies the engine into the game.
- ``AsteriaPlayer`` (no Qt) inside the editor app, under ``player/``: an exported game is a copy
  of it with the game inside, so players need no Python either (``asteria.frozen``).
- ``Asteria-<version>-<platform>.zip`` and, on macOS, a ``.dmg`` with an Applications link.

The macOS app is signed ad-hoc (``--sign IDENTITY`` uses a Developer ID; notarizing is not done
here). ``--skip-player`` / ``--no-archive`` make a quicker build while working on this script.
"""

from __future__ import annotations

import argparse
import compileall
import os
import platform
import shutil
import subprocess
import sys
import sysconfig
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / "src" / "asteria"
WORK = REPO / "build" / "app"
DIST = REPO / "dist"
NAME = "Asteria"
PLAYER = "AsteriaPlayer"
IDENTIFIER = "org.asteria.editor"
# the reference projects the app carries (the Full Verification template is copied from it)
DEMOS = ("full_verification_demo",)
SKIP = ("__pycache__", "*.pyc", ".*.tmp", ".DS_Store", "saves")
# never frozen: test / build tools and modules no Asteria program uses
EXCLUDES = ["tkinter", "turtle", "turtledemo", "idlelib", "test", "pytest", "ruff", "pygbag"]
# the standard library goes in whole (projects may run their own Python), less these
STDLIB_SKIP = {
    "test",
    "tests",
    "idlelib",
    "tkinter",
    "turtledemo",
    "ensurepip",
    "lib2to3",
    "venv",
    "site-packages",
    "__pycache__",
    "__phello__",
    "turtle",
    "this",
    "antigravity",
}

BOOT = '''"""Frozen {kind} entry: put the engine source on sys.path, then run it."""
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # never write into the (signed, maybe read-only) app


def _engine():
    here = Path(sys.executable).resolve().parent
    for folder in (here.parent / "Resources" / "engine", here / "engine"):
        if (folder / "src" / "asteria").is_dir():
            return folder / "src"
    return None


{body}
'''
EDITOR_BODY = """engine = _engine()
if engine is None:
    raise SystemExit("Asteria: the engine folder is missing from the app")
sys.path.insert(0, str(engine))
from asteria.frozen import editor_main  # noqa: E402

raise SystemExit(editor_main())
"""
# the engine a game runs is the one exported with it (game/engine), so the game and its engine
# always match; a project given on the command line brings its own
PLAYER_BODY = """def _game():
    here = Path(sys.executable).resolve().parent
    if len(sys.argv) > 1 and sys.argv[1].endswith(".json"):
        return Path(sys.argv[1]).expanduser().resolve().parent
    for folder in (here.parent / "Resources" / "game", here / "game"):
        if (folder / "project.asteria.json").is_file():
            return folder
    return None


game = _game()
for engine in (game / "engine" if game else None, _engine()):
    if engine is not None and (engine / "asteria").is_dir():
        sys.path.insert(0, str(engine))
        break
else:
    raise SystemExit("AsteriaPlayer: no game here (or it carries no engine)")
from asteria.frozen import player_main  # noqa: E402

raise SystemExit(player_main())
"""

SPEC = """# generated by scripts/build_app.py - do not edit
import sys

block_cipher = None
FILTER = lambda toc: [e for e in toc if not (e[0] == "asteria" or e[0].startswith("asteria."))]


def program(script, name, hidden, excludes, icon_name):
    a = Analysis(
        [script],
        pathex={pathex!r},
        hiddenimports=hidden,
        excludes=excludes,
        noarchive=False,
    )
    a.pure = FILTER(a.pure)  # the engine ships as source beside the program
    pyz = PYZ(a.pure)
    exe = EXE(
        pyz,
        a.scripts,
        [],
        exclude_binaries=True,
        name=name,
        console=False,
        argv_emulation=False,
        target_arch=None,
        codesign_identity=None,
    )
    folder = COLLECT(exe, a.binaries, a.datas, name=name)
    if sys.platform == "darwin":
        BUNDLE(
            folder,
            name=name + ".app",
            bundle_identifier=icon_name,
            version={version!r},
            info_plist={{
                "NSHighResolutionCapable": True,
                "CFBundleShortVersionString": {version!r},
                "LSMinimumSystemVersion": "11.0",
            }},
        )


program({editor_boot!r}, {name!r}, {editor_hidden!r}, {editor_excludes!r}, {identifier!r})
if {with_player!r}:
    program({player_boot!r}, {player!r}, {player_hidden!r}, {player_excludes!r},
            "org.asteria.player")
"""


def version():
    with (REPO / "pyproject.toml").open("rb") as handle:
        return tomllib.load(handle)["project"]["version"]


def platform_tag():
    system = {"darwin": "macos", "win32": "windows"}.get(sys.platform, sys.platform)
    return f"{system}-{platform.machine().lower()}"


def engine_modules(*, editor):
    """Every engine module by name, so PyInstaller freezes what they import (not themselves)."""
    names = []
    for path in sorted(SOURCE.rglob("*.py")):
        parts = path.relative_to(SOURCE.parent).with_suffix("").parts
        if "templates" in parts or "__pycache__" in parts:
            continue  # template folders are data (their scripts build the reference projects)
        if not editor and parts[1:2] == ("editor",):
            continue
        names.append(".".join(parts[:-1] if parts[-1] == "__init__" else parts))
    return names


def stdlib_modules():
    root = Path(sysconfig.get_paths()["stdlib"])
    names = set()
    for path in root.rglob("*.py"):
        relative = path.relative_to(root)
        if STDLIB_SKIP.intersection(relative.parts) or any(
            p.startswith(("test", "_test")) for p in relative.parts
        ):
            continue
        parts = relative.with_suffix("").parts
        if any("-" in p or "." in p for p in parts):
            continue
        names.add(".".join(parts[:-1] if parts[-1] == "__init__" else parts))
    dynload = Path(sysconfig.get_paths()["platstdlib"]) / "lib-dynload"
    for path in dynload.glob("*"):
        name = path.name.split(".")[0]
        if not name.startswith(("_test", "_xx", "xx", "_ctypes_test", "_tkinter")):
            names.add(name)
    return sorted(n for n in names if n and not n.startswith("__"))


def stage_engine(target):
    """``target``/src/asteria (with the native kernel library), asset_library, the demos."""
    from asteria.kernels import build_native

    usable, reason = build_native.ensure()
    if not usable:
        print(f"warning: native kernels not included ({reason}); the slower kernels run")
    shutil.rmtree(target, ignore_errors=True)
    ignore = shutil.ignore_patterns(*SKIP)
    shutil.copytree(SOURCE, target / "src" / "asteria", ignore=ignore)
    if not usable:
        for library in (target / "src" / "asteria" / "kernels" / "native").glob("libasteria*"):
            library.unlink()
    shutil.copytree(REPO / "asset_library", target / "asset_library", ignore=ignore)
    for demo in DEMOS:
        source = REPO / "reference_projects" / demo
        shutil.copytree(source, target / "reference_projects" / demo, ignore=ignore)
    # compiled once here with this (= the frozen) interpreter, so the first start is not slow
    compileall.compile_dir(target / "src", quiet=1, workers=0)


def run_pyinstaller(*, with_player):
    try:
        import PyInstaller  # noqa: F401
    except ImportError:
        raise SystemExit(
            'PyInstaller is missing: .venv/bin/python -m pip install -e ".[package]"'
        ) from None
    WORK.mkdir(parents=True, exist_ok=True)
    editor_boot = WORK / "asteria_editor_boot.py"
    player_boot = WORK / "asteria_player_boot.py"
    editor_boot.write_text(BOOT.format(kind="editor", body=EDITOR_BODY), encoding="utf-8")
    player_boot.write_text(BOOT.format(kind="player", body=PLAYER_BODY), encoding="utf-8")
    stdlib = stdlib_modules()
    spec = WORK / "asteria.spec"
    spec.write_text(
        SPEC.format(
            pathex=[str(REPO / "src")],
            version=version(),
            name=NAME,
            player=PLAYER,
            identifier=IDENTIFIER,
            editor_boot=str(editor_boot),
            player_boot=str(player_boot),
            editor_hidden=engine_modules(editor=True) + stdlib,
            player_hidden=engine_modules(editor=False) + stdlib,
            editor_excludes=EXCLUDES,
            player_excludes=[*EXCLUDES, "PySide6", "shiboken6"],
            with_player=with_player,
        ),
        encoding="utf-8",
    )
    out = WORK / "dist"
    shutil.rmtree(out, ignore_errors=True)
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--log-level=WARN",
        "--distpath",
        str(out),
        "--workpath",
        str(WORK / "work"),
        str(spec),
    ]
    subprocess.run(command, check=True, cwd=WORK)
    return out


def assemble(out, *, with_player):
    """Put the engine (and the player) in the frozen editor; returns the finished app/folder."""
    if sys.platform == "darwin":
        app = out / f"{NAME}.app"
        resources = app / "Contents" / "Resources"
        player = out / f"{PLAYER}.app"
    else:
        app = out / NAME
        resources = app
        player = out / PLAYER
    stage_engine(resources / "engine")
    if with_player:
        shutil.copytree(player, resources / "player" / player.name, symlinks=True)
    final = DIST / app.name
    shutil.rmtree(final, ignore_errors=True)
    DIST.mkdir(exist_ok=True)
    shutil.move(app, final)
    return final


def sign(app, identity):
    if sys.platform != "darwin":
        return
    command = ["codesign", "--force", "--deep", "--sign", identity or "-"]
    if identity:
        command += ["--options", "runtime", "--timestamp"]
    subprocess.run([*command, str(app)], check=True)
    subprocess.run(["codesign", "--verify", "--deep", "--strict", str(app)], check=True)


def archive(app):
    stem = DIST / f"{NAME}-{version()}-{platform_tag()}"
    zip_path = Path(f"{stem}.zip")
    zip_path.unlink(missing_ok=True)
    made = [zip_path]
    if sys.platform == "darwin":
        subprocess.run(
            ["ditto", "-c", "-k", "--sequesterRsrc", "--keepParent", str(app), str(zip_path)],
            check=True,
        )
        staging = WORK / "dmg"
        shutil.rmtree(staging, ignore_errors=True)
        staging.mkdir(parents=True)
        subprocess.run(["ditto", str(app), str(staging / app.name)], check=True)
        os.symlink("/Applications", staging / "Applications")
        dmg = Path(f"{stem}.dmg")
        dmg.unlink(missing_ok=True)
        subprocess.run(
            [
                "hdiutil",
                "create",
                "-quiet",
                "-volname",
                NAME,
                "-srcfolder",
                str(staging),
                "-format",
                "UDZO",
                str(dmg),
            ],
            check=True,
        )
        made.append(dmg)
    else:
        shutil.make_archive(str(stem), "zip", app.parent, app.name)
    return made


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sign", metavar="IDENTITY", help="codesign identity (default: ad-hoc)")
    parser.add_argument("--skip-player", action="store_true", help="no AsteriaPlayer")
    parser.add_argument("--no-archive", action="store_true", help="no .zip / .dmg")
    args = parser.parse_args(argv)
    sys.path.insert(0, str(REPO / "src"))
    with_player = not args.skip_player
    out = run_pyinstaller(with_player=with_player)
    app = assemble(out, with_player=with_player)
    sign(app, args.sign)
    print(f"built {app}")
    if not args.no_archive:
        for path in archive(app):
            print(f"built {path}  ({path.stat().st_size / 1e6:.0f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
