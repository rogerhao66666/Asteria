CONDITION_SOURCES = ("switch", "variable", "local", "rpg", "npc", "battle", "audio")


def _resolve(target):
    module_name, _, path = target.partition(":")
    owner = importlib.import_module(module_name)
    parts = path.split(".")
    for index, part in enumerate(parts):
        if not hasattr(owner, part) and index == len(parts) - 1 and inspect.isclass(owner):
            if _instance_attribute(owner, part):
                return owner, part, "attribute"
        owner_before, owner = owner, getattr(owner, part)  # AttributeError: entry is stale
    if len(parts) > 1 and inspect.isclass(owner_before):
        raw = inspect.getattr_static(owner_before, parts[-1])
        if isinstance(raw, property):
            return owner_before, parts[-1], "property"
        if not callable(raw) and not isinstance(raw, (staticmethod, classmethod)):
            return owner_before, parts[-1], "attribute"
    return owner, parts[-1], "callable"


def _instance_attribute(cls, name):
    """``self.<name> =`` in the class's (or a base's) ``__init__``."""
    for klass in cls.__mro__:
        init = klass.__dict__.get("__init__")
        if init is None:
            continue
        try:
            source = inspect.getsource(init)
        except (OSError, TypeError):
            continue
        if f"self.{name} =" in source or f"self.{name}: " in source:
            return True
    return False


class _Named:
    def __init__(self, name):
        self.name = name

    def __repr__(self):
        return self.name


def _signature(obj):
    target = obj.__init__ if inspect.isclass(obj) else obj
    signature = inspect.signature(target)
    params = []
    for p in signature.parameters.values():
        if p.name in ("self", "cls"):
            continue
        p = p.replace(annotation=inspect.Parameter.empty)
        if p.default is not p.empty and callable(p.default):  # its name, not its address
            p = p.replace(default=_Named(p.default.__name__))
        params.append(p)
    return str(signature.replace(parameters=params, return_annotation=inspect.Signature.empty))


def _row(target, prefix, lang):
    resolved, name, kind = _resolve(target)
    word = {"en": ("property", "attribute"), "zh": ("屬性", "屬性")}[lang]
    if kind == "property":
        shown = f"`{prefix or resolved.__name__ + '.'}{name}` *({word[0]})*"
    elif kind == "attribute":
        shown = f"`{prefix or resolved.__name__ + '.'}{name}` *({word[1]})*"
    else:
        qual = getattr(resolved, "__qualname__", name)
        if prefix and "." in qual:
            qual = prefix + qual.rsplit(".", 1)[1]
        elif "." not in qual:  # a module's function or a class: the name to import
            qual = f"{resolved.__module__}.{qual}"
        shown = f"`{qual}{_signature(resolved)}`"
    return shown.replace("|", "\\|")


def chapter(lang):
    from asteria.runtime.world_command_handlers import WORLD_COMMAND_ARGUMENTS

    zh = lang == "zh"
    head = ("| Signature | Description |", "| 簽名 | 說明 |")[zh]
    out = [BEGIN, ""]
    for number, section in enumerate(SECTIONS, start=1):
        out.append(f"### 15.{number} {section[lang]}")
        out.append("")
        intro = section.get(f"intro_{lang}")
        if intro:
            out += [intro, ""]
        out += [head, "| --- | --- |"]
        for target, en, zh_text, *own in section["items"]:
            prefix = own[0] if own else section["prefix"]  # a member of a member: game.events.
            out.append(f"| {_row(target, prefix, lang)} | {zh_text if zh else en} |")
        out.append("")
    number = len(SECTIONS) + 1
    vm = (ROOT / "src/asteria/events/vm.py").read_text(encoding="utf-8")
    runner = (ROOT / "src/asteria/events/runner.py").read_text(encoding="utf-8")
    out.append(f"### 15.{number} " + ("Event opcodes", "事件指令（opcode）")[zh])
    out.append("")
    out.append(
        (
            "Conditions (`JUMP_IF`, `IF_FALSE_SKIP`, `WAIT until`, event pages) are "
            "`{source, name, operator, value}`; sources: "
            + ", ".join(f"`{s}`" for s in CONDITION_SOURCES)
            + "; operators `==`, `!=`, `<`, `<=`, `>`, `>=`.",
            "條件（`JUMP_IF`、`IF_FALSE_SKIP`、`WAIT until`、事件頁）寫成 "
            "`{source, name, operator, value}`；來源："
            + "、".join(f"`{s}`" for s in CONDITION_SOURCES)
            + "；比較 `==`、`!=`、`<`、`<=`、`>`、`>=`。",
        )[zh]
    )
    out += ["", ("| Opcode | Arguments | Does |", "| Opcode | 參數 | 作用 |")[zh]]
    out.append("| --- | --- | --- |")
    for opcode, args, en, zh_text in OPCODES:
        if f'"{opcode}"' not in vm + runner:
            raise SystemExit(f"opcode {opcode} is not in the event VM or runner")
        cell = args.replace("|", "\\|")
        out.append(f"| `{opcode}` | {cell} | {zh_text if zh else en} |")
    out.append("")
    out.append(f"### 15.{number + 1} " + ("World commands", "世界指令")[zh])
    out.append("")
    out.append(
        (
            f"The {len(WORLD_COMMAND_ARGUMENTS)} commands a `WORLD` instruction can run, with "
            "the argument names each reads (`asteria.runtime.world_command_handlers."
            "WORLD_COMMAND_ARGUMENTS`). In the editor: Events ▸ World.",
            f"`WORLD` 指令可以執行的 {len(WORLD_COMMAND_ARGUMENTS)} 個世界指令與各自讀取的參數名"
            "（`asteria.runtime.world_command_handlers.WORLD_COMMAND_ARGUMENTS`）。"
            "編輯器裡：事件 ▸ 世界。",
        )[zh]
    )
    out += ["", ("| Command | Arguments |", "| 指令 | 參數 |")[zh], "| --- | --- |"]
    for name in sorted(WORLD_COMMAND_ARGUMENTS):
        args = ", ".join(WORLD_COMMAND_ARGUMENTS[name]) or "—"
        out.append(f"| `{name}` | {args} |")
    out += ["", END]
    return "\n".join(out)


def apply(text, lang):
    start, stop = text.index(BEGIN), text.index(END) + len(END)
    return text[:start] + chapter(lang) + text[stop:]


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
    os.environ.setdefault("SDL_AUDIODRIVER", "dummy")
    stale = []
    for lang, path in MANUALS.items():
        text = path.read_text(encoding="utf-8")
        new = apply(text, lang)
        if new != text:
            stale.append(path.name)
            if "--check" not in argv:
                path.write_text(new, encoding="utf-8")
    if "--check" in argv:
        if stale:
            print("out of date:", ", ".join(stale))
            return 1
        print("API chapters match the code")
        return 0
    print("written:", ", ".join(stale) or "nothing changed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
